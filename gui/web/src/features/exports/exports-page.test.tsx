import { http, HttpResponse } from "msw";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { createMemoryRouter, RouterProvider } from "react-router-dom";
import { beforeEach, describe, expect, it, vi } from "vitest";

import type { ArtifactListResponse } from "../../api/client";
import { AppProviders } from "../../app/providers/app-providers";
import { appRoutes } from "../../app/router/routes";
import { server } from "../../test/mocks/server";

const runId = "export-run-123456789012345678901234";
const dbml = "// Generated by ReliFinder\nProject ReliFinder_ERD {\n}\n";
const completeArtifacts: ArtifactListResponse = {
  run_id: runId,
  database_type: "oracle",
  artifacts: [
    {
      id: "relationships-csv",
      type: "csv",
      filename: "relationships.csv",
      available: true,
      size_bytes: 2048,
    },
    {
      id: "analysis-html",
      type: "html",
      filename: "relationship-report.html",
      available: true,
      size_bytes: 4096,
    },
    {
      id: "erd-dbml",
      type: "dbml",
      filename: "full.dbml",
      available: true,
      size_bytes: dbml.length,
      scope: "full",
      min_confidence: 80,
      input_relationships: 30,
      duplicate_relationships_omitted: 0,
      highest_detected_confidence: 92.5,
      below_confidence_threshold: 24,
      omitted_by_validation_filter: 0,
      omitted_by_scope_filter: 0,
      omitted_by_generic_filter: 0,
      omitted_by_limit: 1,
      eligible_relationships: 5,
      rendered_relationships: 4,
      unknown_cardinality_omitted: 1,
    },
  ],
};

function installApi(payload = completeArtifacts) {
  server.use(
    http.get("/api/runs/:runId/artifacts", () => HttpResponse.json(payload)),
    http.get(
      "/api/runs/:runId/artifacts/erd-dbml",
      () =>
        new HttpResponse(dbml, {
          headers: { "Content-Length": String(dbml.length), "Content-Type": "text/plain" },
        }),
    ),
  );
}

function renderExports() {
  return render(
    <AppProviders>
      <RouterProvider
        router={createMemoryRouter(appRoutes, {
          initialEntries: [`/exports?run=${runId}`],
        })}
      />
    </AppProviders>,
  );
}

beforeEach(() => {
  Object.defineProperty(navigator, "clipboard", {
    configurable: true,
    value: { writeText: vi.fn().mockResolvedValue(undefined) },
  });
});

describe("completed-run exports", () => {
  it("lists exact CSV/HTML/DBML actions and explains DBML omissions", async () => {
    installApi();
    renderExports();

    expect(await screen.findByRole("heading", { name: "Artifacts & DBML" })).toBeInTheDocument();
    const csv = screen.getByRole("link", { name: "Download CSV" });
    expect(csv).toHaveAttribute(
      "href",
      `/api/runs/${runId}/artifacts/relationships-csv?download=true`,
    );
    const openReport = screen.getByRole("link", { name: "Open Report" });
    expect(openReport).toHaveAttribute("href", `/api/runs/${runId}/artifacts/analysis-html`);
    expect(openReport).toHaveAttribute("target", "_blank");
    expect(screen.getByRole("link", { name: "Download HTML" })).toHaveAttribute(
      "href",
      `/api/runs/${runId}/artifacts/analysis-html?download=true`,
    );
    expect(await screen.findByRole("heading", { name: "DBML Code" })).toBeInTheDocument();
    expect(
      screen.getByText(
        (_content, element) =>
          element?.tagName === "CODE" &&
          element.textContent?.includes("Project ReliFinder_ERD {") === true,
      ),
    ).toBeInTheDocument();
    expect(screen.getByText("Rendered DBML references").nextSibling).toHaveTextContent("4");
    expect(screen.getByText("Unknown cardinality omitted").nextSibling).toHaveTextContent("1");
    expect(screen.getByText(/not the current transient GUI filter/i)).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Open dbdiagram" })).toHaveAttribute(
      "href",
      "https://dbdiagram.io/",
    );
    expect(screen.getAllByRole("link", { name: "Download DBML" })[0]).toHaveAttribute(
      "href",
      `/api/runs/${runId}/artifacts/erd-dbml?download=true`,
    );
  });

  it("explains an empty DBML with authoritative threshold diagnostics", async () => {
    const emptyArtifacts: ArtifactListResponse = {
      ...completeArtifacts,
      artifacts: completeArtifacts.artifacts.map((artifact) =>
        artifact.type === "dbml"
          ? {
              ...artifact,
              min_confidence: 80,
              highest_detected_confidence: 55.04,
              below_confidence_threshold: 30,
              eligible_relationships: 0,
              rendered_relationships: 0,
              unknown_cardinality_omitted: 0,
            }
          : artifact,
      ),
    };
    installApi(emptyArtifacts);
    renderExports();

    expect(
      await screen.findByText("No relationships qualified for this DBML export."),
    ).toBeInTheDocument();
    expect(screen.getByText("Highest detected confidence").nextSibling).toHaveTextContent("55.04");
    expect(screen.getByText("Below threshold").nextSibling).toHaveTextContent("30");
    expect(screen.getByText("Unknown cardinality omitted").nextSibling).toHaveTextContent("0");
  });

  it("regenerates DBML from completed artifacts and refreshes preview and download", async () => {
    const user = userEvent.setup();
    const regeneratedDbml = "// Minimum confidence: 40\nProject ReliFinder_ERD {\n}\n";
    const generated = {
      ...completeArtifacts.artifacts[2]!,
      id: "erd-dbml-regenerated",
      filename: "full.dbml",
      min_confidence: 40,
      size_bytes: regeneratedDbml.length,
      eligible_relationships: 16,
      rendered_relationships: 8,
      unknown_cardinality_omitted: 8,
    };
    let posted: unknown;
    installApi();
    server.use(
      http.post("/api/runs/:runId/exports/dbml", async ({ request }) => {
        posted = await request.json();
        return HttpResponse.json({
          run_id: runId,
          database_type: "postgresql",
          generated_artifact_ids: [generated.id],
          artifacts: [...completeArtifacts.artifacts, generated],
        });
      }),
      http.get(
        "/api/runs/:runId/artifacts/erd-dbml-regenerated",
        () =>
          new HttpResponse(regeneratedDbml, {
            headers: {
              "Content-Length": String(regeneratedDbml.length),
              "Content-Type": "text/plain",
            },
          }),
      ),
    );
    renderExports();
    await screen.findByRole("heading", { name: "DBML Code" });

    const threshold = screen.getByLabelText("DBML minimum confidence");
    await user.clear(threshold);
    await user.type(threshold, "40");
    await user.click(screen.getByRole("button", { name: "Regenerate DBML" }));

    expect(
      await screen.findByText(
        (_content, element) =>
          element?.tagName === "CODE" &&
          element.textContent?.includes("Minimum confidence: 40") === true,
      ),
    ).toBeInTheDocument();
    expect(posted).toEqual({ min_confidence: 40 });
    expect(screen.getAllByRole("link", { name: "Download DBML" }).at(-1)).toHaveAttribute(
      "href",
      `/api/runs/${runId}/artifacts/${generated.id}?download=true`,
    );
  });
  it("copies DBML only after explicit user action", async () => {
    const user = userEvent.setup();
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, "clipboard", {
      configurable: true,
      value: { writeText },
    });
    installApi();
    renderExports();
    await screen.findByRole("heading", { name: "DBML Code" });

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(writeText).toHaveBeenCalledWith(dbml);
    expect(await screen.findByRole("button", { name: "Copied" })).toBeInTheDocument();
  });
  it("handles clipboard denial without losing the viewer", async () => {
    const user = userEvent.setup();
    Object.defineProperty(navigator, "clipboard", {
      configurable: true,
      value: { writeText: vi.fn().mockRejectedValue(new Error("denied")) },
    });
    installApi();
    renderExports();
    await screen.findByRole("heading", { name: "DBML Code" });

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(await screen.findByRole("alert")).toHaveTextContent(/clipboard access failed/i);
    expect(
      screen.getByText(
        (_content, element) =>
          element?.tagName === "CODE" &&
          element.textContent?.includes("Project ReliFinder_ERD {") === true,
      ),
    ).toBeInTheDocument();
  });

  it("keeps large DBML downloadable while declining an oversized preview", async () => {
    installApi();
    server.use(
      http.get(
        "/api/runs/:runId/artifacts/erd-dbml",
        () =>
          new HttpResponse("preview skipped", {
            headers: { "Content-Length": "6000000", "Content-Type": "text/plain" },
          }),
      ),
    );
    renderExports();

    expect(await screen.findByRole("alert")).toHaveTextContent(
      /DBML is too large to preview; download it instead/i,
    );
    expect(screen.getAllByRole("link", { name: "Download DBML" }).length).toBeGreaterThan(0);
  });
  it("shows unavailable artifacts without enabling unsafe actions", async () => {
    installApi({
      run_id: runId,
      database_type: "oracle",
      artifacts: completeArtifacts.artifacts.map((artifact) =>
        artifact.type === "dbml" ? { ...artifact, available: false, size_bytes: null } : artifact,
      ),
    });
    renderExports();

    expect(await screen.findByText(/DBML was not generated/i)).toBeInTheDocument();
    expect(screen.getByText("Not generated or invalid")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Copy" })).not.toBeInTheDocument();
  });

  it("does not enable exports for a failed or incomplete run", async () => {
    server.use(
      http.get("/api/runs/:runId/artifacts", () =>
        HttpResponse.json(
          {
            error: {
              code: "RUN_NOT_COMPLETED",
              message: "Artifacts are available only for a completed analysis run.",
            },
          },
          { status: 409 },
        ),
      ),
    );
    renderExports();

    expect(await screen.findByRole("heading", { name: "Exports unavailable" })).toBeInTheDocument();
    expect(screen.getByText(/only for a completed analysis run/i)).toBeInTheDocument();
    expect(screen.queryByRole("link", { name: /Download/ })).not.toBeInTheDocument();
  });
});
